"""Journal: turn the decision log into something a human reads.

`daily_report()` builds a markdown summary from SQLite; `publish_daily_note()` writes it
into the terminal's Notes screen once per trading day (tracked in meta so a long-running
loop posts it exactly once).
"""
from __future__ import annotations

import logging
import time
from collections import Counter
from datetime import datetime
from zoneinfo import ZoneInfo

from .config import Config
from .rules import day_start_epoch
from .state import State
from .terminal_client import TerminalClient, TerminalError

log = logging.getLogger("headline_algo.journal")


def _fmt_ts(ts: float, tz: str) -> str:
    return datetime.fromtimestamp(ts, ZoneInfo(tz)).strftime("%H:%M")


def daily_report(cfg: Config, state: State, since: float | None = None) -> str:
    since = since if since is not None else day_start_epoch(cfg)
    tz = cfg.market_tz
    decisions = state.decisions_since(since)
    trades = state.closed_trades_since(since)
    open_pos = state.open_positions()
    buys = [d for d in decisions if d["action"] == "buy"]
    closes = [d for d in decisions if d["action"] == "close"]
    skips = [d for d in decisions if d["action"] == "skip"]
    skip_reasons = Counter(d["reason"].split(":")[0] for d in skips)
    event_types = Counter(d["event_type"] for d in decisions if d["event_type"])
    realised = sum(float(t["pnl"] or 0.0) for t in trades)
    wins = sum(1 for t in trades if (t["pnl"] or 0.0) > 0)

    lines = [
        f"# Headline algo — {datetime.fromtimestamp(since, ZoneInfo(tz)).strftime('%Y-%m-%d')} ({tz})",
        "",
        f"Decisions: **{len(decisions)}** · entries **{len(buys)}** · closes **{len(closes)}** · skips **{len(skips)}**",
        f"Closed trades: **{len(trades)}** · wins **{wins}** · realised P&L **{realised:+.2f}**",
        f"Open positions: **{len(open_pos)}**",
        "",
    ]
    if event_types:
        lines.append("## Event types seen")
        for et, n in event_types.most_common():
            lines.append(f"- {et}: {n}")
        lines.append("")
    if buys:
        lines.append("## Entries")
        for d in buys:
            lines.append(f"- {_fmt_ts(d['decided_at'], tz)} **{d['symbol']}** — {d['event_type']} "
                         f"({d['direction']}, conf {d['confidence']:.2f})")
        lines.append("")
    if trades:
        lines.append("## Closed")
        for t in trades:
            px = f"{t['exit_price']:.2f}" if t["exit_price"] is not None else "n/a"
            pnl = f"{t['pnl']:+.2f}" if t["pnl"] is not None else "n/a"
            lines.append(f"- **{t['symbol']}** {t['exit_reason']} · entry {t['entry_price']:.2f} → exit {px} · P&L {pnl}")
        lines.append("")
    if open_pos:
        lines.append("## Open")
        for p in open_pos:
            lines.append(f"- **{p['symbol']}** x{p['quantity']:.0f} @ {p['entry_price']:.2f} · stop {p['stop_price']:.2f} "
                         f"· target {p['target_price']:.2f} · exit by {_fmt_ts(p['exit_by'], tz)}")
        lines.append("")
    if skip_reasons:
        lines.append("## Why trades were skipped")
        for r, n in skip_reasons.most_common(12):
            lines.append(f"- {r}: {n}")
        lines.append("")
    lines.append("_Paper only. Generated by headline_algo; every row above is in the local SQLite decision log._")
    return "\n".join(lines)


def publish_daily_note(cfg: Config, state: State, client: TerminalClient, *, force: bool = False) -> bool:
    """Post today's report to Notes once per day (or whenever `force`)."""
    day_key = datetime.now(ZoneInfo(cfg.market_tz)).strftime("%Y-%m-%d")
    if not force and state.get_meta("last_note_day") == day_key:
        return False
    body = daily_report(cfg, state)
    tickers = sorted({d["symbol"] for d in state.decisions_since(day_start_epoch(cfg)) if d["symbol"]})
    try:
        client.create_note(f"Headline algo daily — {day_key}", body, tickers=",".join(tickers[:20]))
    except TerminalError as exc:
        log.warning("could not publish note: %s", exc)
        return False
    state.set_meta("last_note_day", day_key)
    return True


def status_text(cfg: Config, state: State) -> str:
    since = day_start_epoch(cfg)
    decisions = state.decisions_since(since)
    return (f"portfolio={cfg.portfolio_id or '(unset)'} extract={cfg.extract.backend} "
            f"open={len(state.open_positions())} decisions_today={len(decisions)} "
            f"realised_today={state.realised_pnl_since(since):+.2f} "
            f"last_cycle={state.get_meta('last_cycle_at', 'never')} "
            f"last_note={state.get_meta('last_note_day', 'never')} at {time.strftime('%H:%M:%S')}")
